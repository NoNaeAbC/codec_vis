#!/usr/bin/env python3
"""Import real TFLite link dependencies from the matching AVM Ninja build.

Usage: python3 scripts/configure_avm_runtime.py /path/to/avm/build
Only writes build/avm-runtime.mk in this repository; never modifies AVM.
"""
import hashlib
from pathlib import Path
import shlex
import subprocess
import sys

base = Path(sys.argv[1]).resolve()
text = (base / 'build.ninja').read_text()
section = text[text.index('build avmenc:'):]
line = next(s for s in section.splitlines() if s.startswith('  LINK_LIBRARIES ='))
libs = []
for item in shlex.split(line.split('=', 1)[1]):
    if item.endswith('.a') and item != 'libavm.a':
        path = base / item
        if not path.is_file():
            raise SystemExit(f'Missing dependency: {path}')
        if any(c in str(path) for c in ' \t\n#$'):
            raise SystemExit('Make dependency paths must not contain whitespace, #, or $')
        libs.append(str(path))
    elif item.startswith('-'):
        libs.append(item)
# These archives must match the installed AVM that pkg-config will link.
prefix = subprocess.check_output(['pkg-config', '--variable=libdir', 'avm'], text=True).strip()
digest = lambda p: hashlib.sha256(Path(p).read_bytes()).digest()
if digest(Path(prefix) / 'libavm.a') != digest(base / 'libavm.a'):
    raise SystemExit('Installed libavm.a differs from this AVM build; refusing dependency import')
Path('build').mkdir(exist_ok=True)
Path('build/avm-runtime.mk').write_text(
    '# Generated by scripts/configure_avm_runtime.py; local dependency paths.\n'
    'AVM_TFLITE_LIBS := -Wl,--start-group ' + ' '.join(libs) + ' -Wl,--end-group\n')
print('Configured real AVM/TFLite dependencies in build/avm-runtime.mk')
